// Command gen-docs renders CLAUDE.md and README.md from their templates, filling in
// task descriptions from Taskfile.yml, package docs from go list, and exported component
// documentation scraped via go doc.
package main

import (
	"bytes"
	"cmp"
	"context"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"text/template"
)

type goModule struct {
	Path string `json:"Path"`
}

type goPackage struct {
	ImportPath string   `json:"ImportPath"`
	Doc        string   `json:"Doc"`
	Module     goModule `json:"Module"`
}

type docPackage struct {
	ImportPath string
	Doc        string
}

type taskLocation struct {
	Line int `json:"line"`
}

type rawTask struct {
	Name     string       `json:"name"`
	Desc     string       `json:"desc"`
	Location taskLocation `json:"location"`
}

type taskListResult struct {
	Tasks []rawTask `json:"tasks"`
}

type taskInfo struct {
	Name string
	Desc string
}

// componentDoc holds the documentation for one exported component constructor.
type componentDoc struct {
	Name string
	Doc  string
}

type templateData struct {
	Packages   []docPackage
	Tasks      []taskInfo
	Components []componentDoc
}

const (
	claudeTemplRelPath = "scripts/gen-docs/CLAUDE.md.tmpl"
	readmeTemplRelPath = "scripts/gen-docs/README.md.tmpl"
	outputFileMode     = 0o600

	generatedWarning = `<!--
This file is generated by scripts/gen-docs.
Do not hand-edit — edit the template, then run the appropriate task to regenerate.
-->
`
)

func main() {
	err := run()
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen-docs:", err)
		os.Exit(1)
	}
}

func run() error {
	ctx := context.Background()

	root, err := repoRoot(ctx)
	if err != nil {
		return fmt.Errorf("locating repo root: %w", err)
	}

	packages, err := listPackages(ctx, root)
	if err != nil {
		return fmt.Errorf("listing packages: %w", err)
	}

	tasks, err := listTasks(ctx, root)
	if err != nil {
		return fmt.Errorf("listing tasks: %w", err)
	}

	components, err := listComponents(ctx, root)
	if err != nil {
		return fmt.Errorf("listing components: %w", err)
	}

	data := templateData{Packages: packages, Tasks: tasks, Components: components}

	err = renderTemplate(root, claudeTemplRelPath, "CLAUDE.md", data)
	if err != nil {
		return err
	}

	err = renderTemplate(root, readmeTemplRelPath, "README.md", data)
	if err != nil {
		return err
	}

	return nil
}

func renderTemplate(root, tmplRelPath, outName string, data templateData) error {
	tmplPath := filepath.Join(root, tmplRelPath)

	tmpl, err := template.ParseFiles(tmplPath)
	if err != nil {
		return fmt.Errorf("parsing %s: %w", tmplPath, err)
	}

	var out bytes.Buffer

	err = tmpl.Execute(&out, data)
	if err != nil {
		return fmt.Errorf("rendering %s: %w", tmplRelPath, err)
	}

	outPath := filepath.Join(root, outName)

	err = os.WriteFile(outPath, withGeneratedWarning(out.Bytes()), outputFileMode)
	if err != nil {
		return fmt.Errorf("writing %s: %w", outPath, err)
	}

	return nil
}

func withGeneratedWarning(rendered []byte) []byte {
	title, body, found := bytes.Cut(rendered, []byte("\n"))
	if !found {
		return rendered
	}

	return []byte(string(title) + "\n\n" + generatedWarning + string(body))
}

func repoRoot(ctx context.Context) (string, error) {
	out, err := exec.CommandContext(ctx, "go", "env", "GOMOD").Output()
	if err != nil {
		return "", err
	}

	return filepath.Dir(strings.TrimSpace(string(out))), nil
}

func listPackages(ctx context.Context, root string) ([]docPackage, error) {
	cmd := exec.CommandContext(ctx, "go", "list", "-json", "./pkg/...", "./cmd/...")
	cmd.Dir = root

	out, err := cmd.Output()
	if err != nil {
		return nil, err
	}

	var packages []docPackage

	decoder := json.NewDecoder(bytes.NewReader(out))
	for decoder.More() {
		var pkg goPackage

		err := decoder.Decode(&pkg)
		if err != nil {
			return nil, err
		}

		d := strings.TrimSpace(pkg.Doc)
		if !strings.HasPrefix(d, "Package ") && !strings.HasPrefix(d, "Command ") {
			continue
		}

		importPath := strings.TrimPrefix(pkg.ImportPath, pkg.Module.Path+"/")
		packages = append(packages, docPackage{ImportPath: importPath, Doc: d})
	}

	slices.SortFunc(packages, func(a, b docPackage) int {
		return cmp.Compare(a.ImportPath, b.ImportPath)
	})

	return packages, nil
}

func listTasks(ctx context.Context, root string) ([]taskInfo, error) {
	cmd := exec.CommandContext(ctx, "task", "--list-all", "--json")
	cmd.Dir = root

	out, err := cmd.Output()
	if err != nil {
		return nil, err
	}

	var result taskListResult

	err = json.Unmarshal(out, &result)
	if err != nil {
		return nil, err
	}

	slices.SortFunc(result.Tasks, func(a, b rawTask) int {
		return cmp.Compare(a.Location.Line, b.Location.Line)
	})

	tasks := make([]taskInfo, len(result.Tasks))
	for i, t := range result.Tasks {
		tasks[i] = taskInfo{Name: t.Name, Desc: t.Desc}
	}

	return tasks, nil
}

// constructorRE matches a go doc line declaring a func that returns templ.Component.
var constructorRE = regexp.MustCompile(`^func ([A-Z]\w+)\(.*\) templ\.Component$`)

// listComponents scrapes the exported API of pkg/ via go doc, extracting every function
// that returns templ.Component along with its doc comment and signature.
func listComponents(ctx context.Context, root string) ([]componentDoc, error) {
	cmd := exec.CommandContext(ctx, "go", "doc", "-all", "./pkg/")
	cmd.Dir = root

	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go doc ./pkg/: %w", err)
	}

	var components []componentDoc

	lines := strings.Split(string(out), "\n")

	for i, line := range lines {
		m := constructorRE.FindStringSubmatch(strings.TrimSpace(line))
		if m == nil {
			continue
		}

		name := m[1]
		docComment := extractFollowingDoc(lines, i)

		components = append(components, componentDoc{
			Name: name,
			Doc:  docComment,
		})
	}

	slices.SortFunc(components, func(a, b componentDoc) int {
		return cmp.Compare(a.Name, b.Name)
	})

	return components, nil
}

// extractFollowingDoc walks forward from line i+1 to collect the indented doc comment block.
func extractFollowingDoc(lines []string, i int) string {
	var docLines []string

	for j := i + 1; j < len(lines); j++ {
		line := lines[j]

		if !strings.HasPrefix(line, "    ") {
			break
		}

		docLines = append(docLines, strings.TrimSpace(line))
	}

	return strings.Join(docLines, " ")
}
